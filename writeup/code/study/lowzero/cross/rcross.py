"""Registered analysis of the cross-correlation test (round_draft.txt). NOT RUN on real zeros before the registration
is committed. usage: rcross.py DESIGN [ZEROFILE_NEW]   DESIGN in NN NO OO
  zero sets: lzeros/r138_Fn.npz (new, keys 'D%d'), the old sets R120 (r117/r120 parts), r134_B.npz, r136_Dn.npz;
  ZEROFILE_NEW replaces the new file (synthetic dry runs). Completeness rule of round 138 (|N - theta/pi| <= 1.5 at 200
  heights, largest unfolded gap <= 3.0) on [100, 600]; a flagged set is excluded with all its pairs (reported).
  Statistic: C_ij(w) = mean_t dn_i(t) dn_j(t), w = 0.3 k, t = 100 + 0.02 j <= 600 - w (crosslib.dn_series).
  Readings: readings.py with the frozen predictions (predictions_cross.json / predictions_cross_pairs.npz, sha256
  checked) and the swapped-term predictor (swap_pred_DESIGN.npz, sha256 checked; zeros elsewhere)."""
import os, sys, json, math, hashlib
import numpy as np
from scipy import stats
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from crosslib import *
from readings import readings
REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..', '..')); ZD = os.path.join(REPO, 'writeup/data/riemann/lzeros')
REG = {'json': None, 'pairs': None, 'swap_NN': None, 'swap_NO': None}      # sha256 values written into the registration
DES = sys.argv[1]; JS = json.load(open(os.path.join(HERE, 'predictions_cross.json')))
sha = hashlib.sha256(open(os.path.join(HERE, 'predictions_cross_pairs.npz'), 'rb').read()).hexdigest(); assert sha == JS['pairs_sha256']
T1, T2, H = JS['T1'], JS['T2'], JS['h']; W = np.array(JS['w']); A_T = np.array(JS['A_T']).T; B_T = np.array(JS['B_T']).T
NEW = JS['design']['new_Fn']; OLD = JS['design']['old']
def load(files):
    Z = {}
    for f in files:
        z = np.load(f); Z.update({k: z[k] for k in z.files})
    return Z
ZN = load([sys.argv[2] if len(sys.argv) > 2 else os.path.join(ZD, 'r138_Fn.npz')])
ZO = load([os.path.join(ZD, f) for f in ('r117_part0.npz', 'r117_part1.npz', 'r120_part0.npz', 'r120_part1.npz', 'r134_B.npz', 'r136_Dn.npz')]) if DES != 'NN' else {}
DRY = os.environ.get('CROSS_DRYRUN') == '1'      # synthetic dry run: no completeness rule (Poisson sets would all fail it)
def complete(g, D):
    q = abs(D); a = 0 if D > 0 else 1; t = np.linspace(T1, T2, 200); s = np.searchsorted(g, t) - (theta(t, q, a) - theta(0.0, q, a)) / math.pi
    b = g[(g >= T1) & (g <= T2)]; u = b / (2 * math.pi) * np.log(q * b / (2 * math.pi * math.e)); return float(np.abs(s).max()), float(np.diff(u).max())
def series(Ds, Z):
    keep, excl, S = [], [], []
    for D in Ds:
        g = np.sort(Z['D%d' % D]); s, gap = complete(g, D)
        if (s > 1.5 or gap > 3.0) and not DRY: excl.append((D, round(s, 2), round(gap, 2))); continue
        keep.append(D); S.append(g)
    return keep, excl, S
A_ = NEW if DES in ('NN', 'NO') else OLD; B_ = NEW if DES == 'NN' else OLD
ka, ea, Ga = series(A_, ZN if DES in ('NN', 'NO') else ZO); kb, eb, Gb = (ka, ea, Ga) if DES in ('NN', 'OO') else series(B_, ZO)
print('design %s: excluded %s %s' % (DES, ea, eb if DES == 'NO' else ''))
P = np.load(os.path.join(HERE, 'predictions_cross_pairs.npz'))
if DES == 'OO':
    raise SystemExit('OO predictions are regenerated by predict.py (not stored); add them before running test O')
D1 = P[DES + '_D1']; D2 = P[DES + '_D2']; F = P[DES + '_full'].T.astype(float); R = P[DES + '_rest'].T.astype(float); PSI = P[DES + '_psi'].astype(float)
ia = {D: i for i, D in enumerate(ka)}; ib = {D: i for i, D in enumerate(kb)}
ok = np.array([(int(a) in ia) and (int(b) in ib) for a, b in zip(D1, D2)])
D1, D2, F, R, PSI = D1[ok], D2[ok], F[:, ok], R[:, ok], PSI[ok]
SW = np.zeros_like(F); fsw = os.path.join(HERE, 'swap_pred_%s.npz' % DES)
if os.path.exists(fsw):
    s = np.load(fsw); key = {(int(a), int(b)): c for a, b, c in zip(s['D1'], s['D2'], s['C'])}
    for n, (a, b) in enumerate(zip(D1, D2)):
        c = key.get((int(a), int(b)), key.get((int(b), int(a))))
        if c is not None: SW[:, n] = c
C = np.zeros_like(F)
for k, w in enumerate(W):
    M = int(math.floor((T2 - w - T1) / H + 1e-9)) + 1; tg = T1 + H * np.arange(M)
    Sa = np.array([dn_series(g, abs(D), 0 if D > 0 else 1, w, tg) for D, g in zip(ka, Ga)])
    Sb = Sa if DES == 'NN' else np.array([dn_series(g, abs(D), 0 if D > 0 else 1, w, tg) for D, g in zip(kb, Gb)])
    Cm = Sa @ Sb.T / M
    C[k] = np.array([Cm[ia[int(a)], ib[int(b)]] for a, b in zip(D1, D2)])
I = np.array([ia[int(a)] for a in D1]); J = np.array([ib[int(b)] + (0 if DES == 'NN' else 10 ** 6) for b in D2])
r, se, cov_s = readings(C, PSI, R, F, A_T, B_T, SWAP=SW, I=I, J=J, jack=True)
E = JS['expected_readings'][DES]['H_law']
print('readings (value, jackknife se, expected under H_law, z against H_law, z against H_indep):')
for k in ('gamma_2', 'gamma_3', 'gamma_5', 'gamma_7', 'gammaB_2', 'gammaB_3', 'gamma_rest', 'gamma_full', 'small_w', 'gamma_sw'):
    if k in r:
        e = E.get(k, 1.0); print('  %-10s %+.4f  se %.4f  exp %+.4f  z_law %+.1f  z_indep %+.1f' % (k, r[k], se[k], e, (r[k] - e) / se[k], r[k] / se[k]))
crit = float(stats.chi2.ppf(0.999, 16)); chi = {}
for a, p in enumerate((2, 3)):
    d = np.array(r['s'])[:, a] - np.array(E['per_w_s'])[:, a]; Ci = np.linalg.pinv(np.array(cov_s[a])); chi[p] = float(d @ Ci @ d)
    print('  shape chi2 p=%d: %.1f (0.1%% point %.1f)' % (p, chi[p], crit))
print('  intercepts / se: ' + ' '.join('%+.1f' % (v / s) for v, s in zip(r['icpt'], se['icpt'])))
dec = {'law_passes': all(abs(r[k] - E.get(k, 1)) <= 4 * se[k] for k in ('gamma_2', 'gamma_3', 'gamma_5', 'gamma_7', 'gamma_full')) and chi[2] < crit and chi[3] < crit,
       'indep_rejected': r['gamma_full'] >= 5 * se['gamma_full'] and r['gamma_2'] >= 5 * se['gamma_2'],
       'flip_rejected': (r['gamma_full'] + 1) >= 5 * se['gamma_full']}
if 'gamma_sw' in r: dec['swap_law_passes'] = abs(r['gamma_sw'] - 1) <= 4 * se['gamma_sw']; dec['swap_absent_rejected'] = r['gamma_sw'] >= 5 * se['gamma_sw']
print('decisions', dec)
json.dump({'design': DES, 'readings': {k: v for k, v in r.items()}, 'se': se, 'chi2_shape': chi, 'decisions': dec, 'excluded': [ea, eb]},
          open(os.path.join(HERE, 'rcross_%s.json' % DES), 'w'))
